# =============================================================================

generate_weekly_maintenance() {
    cat << 'EOF'
#!/bin/bash
# =============================================================================
# MCP Weekly Maintenance Tasks
# =============================================================================
# - Database VACUUM and optimization
# - Security update checks
# - Certificate expiration checks
# - Backup verification
# =============================================================================

set -euo pipefail

readonly LOG_DIR="/var/log/mcp"
readonly CERT_WARNING_DAYS=30

log() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*" | tee -a "${LOG_DIR}/weekly-maintenance.log"
}

# Database maintenance (for database VMs)
database_maintenance() {
    if ! systemctl is-active --quiet postgresql; then
        log "PostgreSQL not running on this VM, skipping database maintenance"
        return 0
    fi

    log "Starting database maintenance..."

    # VACUUM all databases
    log "Running VACUUM ANALYZE on all databases..."

    sudo -u postgres psql -c "SELECT datname FROM pg_database WHERE datistemplate = false;" -t | while read -r dbname; do
        dbname=$(echo "$dbname" | xargs)
        [ -z "$dbname" ] && continue

        log "VACUUM ANALYZE on database: $dbname"
        sudo -u postgres psql -d "$dbname" -c "VACUUM ANALYZE;" 2>&1 | tee -a "${LOG_DIR}/weekly-maintenance.log"
    done

    # Reindex critical tables
    log "Reindexing system catalogs..."
    sudo -u postgres psql -d postgres -c "REINDEX SYSTEM postgres;" 2>&1 | tee -a "${LOG_DIR}/weekly-maintenance.log"

    # Update statistics
    log "Updating planner statistics..."
    sudo -u postgres psql -d postgres -c "ANALYZE;" 2>&1 | tee -a "${LOG_DIR}/weekly-maintenance.log"

    # Check for bloated tables
    log "Checking for table bloat..."
    sudo -u postgres psql -d postgres << 'SQL' | tee -a "${LOG_DIR}/weekly-maintenance.log"
SELECT
    schemaname,
    tablename,
    pg_size_pretty(pg_total_relation_size(schemaname||'.'||tablename)) AS size
FROM pg_tables
WHERE schemaname NOT IN ('pg_catalog', 'information_schema')
ORDER BY pg_total_relation_size(schemaname||'.'||tablename) DESC
LIMIT 10;
SQL

    log "Database maintenance completed"
}

# Check for security updates
check_security_updates() {
    log "Checking for security updates..."

    if command -v apt-get &> /dev/null; then
        # Debian/Ubuntu
        apt-get update -qq
        local security_updates=$(apt-get upgrade -s | grep -i security | wc -l)

        if [ "$security_updates" -gt 0 ]; then
            log "WARNING: $security_updates security updates available"
            apt-get upgrade -s | grep -i security | tee -a "${LOG_DIR}/weekly-maintenance.log"
            logger -p daemon.warning "MCP: $security_updates security updates available"
        else
            log "System is up to date with security patches"
        fi

    elif command -v yum &> /dev/null; then
        # RHEL/CentOS
        local security_updates=$(yum updateinfo list security 2>/dev/null | grep -c 'security' || echo 0)

        if [ "$security_updates" -gt 0 ]; then
            log "WARNING: $security_updates security updates available"
            yum updateinfo list security | tee -a "${LOG_DIR}/weekly-maintenance.log"
            logger -p daemon.warning "MCP: $security_updates security updates available"
        else
            log "System is up to date with security patches"
        fi
    fi
}

# Check SSL certificate expiration
check_certificates() {
    log "Checking SSL certificate expiration..."

    local cert_dirs=("/etc/ssl/certs" "/etc/nginx/ssl" "/etc/letsencrypt/live")
    local warning_count=0

    for cert_dir in "${cert_dirs[@]}"; do
        if [ ! -d "$cert_dir" ]; then
            continue
        fi

        find "$cert_dir" -name "*.crt" -o -name "*.pem" 2>/dev/null | while read -r cert; do
            if openssl x509 -in "$cert" -noout -text &> /dev/null; then
                local expiry_date=$(openssl x509 -in "$cert" -noout -enddate | cut -d= -f2)
                local expiry_epoch=$(date -d "$expiry_date" +%s 2>/dev/null || date -j -f "%b %d %H:%M:%S %Y %Z" "$expiry_date" +%s 2>/dev/null || echo 0)
                local now_epoch=$(date +%s)
                local days_until_expiry=$(( (expiry_epoch - now_epoch) / 86400 ))

                if [ "$days_until_expiry" -lt "$CERT_WARNING_DAYS" ] && [ "$days_until_expiry" -gt 0 ]; then
                    log "WARNING: Certificate $cert expires in $days_until_expiry days"
                    logger -p daemon.warning "MCP: SSL certificate $cert expires in $days_until_expiry days"
                    ((warning_count++)) || true
                elif [ "$days_until_expiry" -le 0 ]; then
                    log "CRITICAL: Certificate $cert has EXPIRED"
                    logger -p daemon.crit "MCP: SSL certificate $cert has expired"
                    ((warning_count++)) || true
                fi
            fi
        done
    done

    if [ "$warning_count" -eq 0 ]; then
        log "All certificates valid for at least $CERT_WARNING_DAYS days"
    fi
}

# Verify backup health
verify_backups() {
    log "Verifying backup health..."

    local backup_dir="/mnt/storage/backups"

    if [ ! -d "$backup_dir" ]; then
        log "Backup directory not found on this VM"
        return 0
    fi

    # Check latest backup age
    local latest_backup=$(find "$backup_dir" -type f -printf '%T@ %p\n' 2>/dev/null | sort -rn | head -1 | cut -d' ' -f2)

    if [ -n "$latest_backup" ]; then
        local age=$(( $(date +%s) - $(stat -c %Y "$latest_backup" 2>/dev/null || stat -f %m "$latest_backup") ))
        local age_hours=$((age / 3600))

        log "Latest backup: $(basename "$latest_backup"), age: ${age_hours}h"

        if [ "$age_hours" -gt 48 ]; then
            log "WARNING: Latest backup is more than 48 hours old"
            logger -p daemon.warning "MCP: Latest backup is ${age_hours} hours old"
        else
            log "Backup freshness OK"
        fi
    else
        log "WARNING: No backups found"
        logger -p daemon.warning "MCP: No backups found in $backup_dir"
    fi

    # Check backup disk usage
    local backup_usage=$(df -h "$backup_dir" | tail -1 | awk '{print $5}' | sed 's/%//')
    log "Backup storage usage: ${backup_usage}%"

    if [ "$backup_usage" -gt 85 ]; then
        log "WARNING: Backup storage usage is high (${backup_usage}%)"
        logger -p daemon.warning "MCP: Backup storage usage is ${backup_usage}%"
    fi
}

# Main execution
main() {
    log "Starting weekly maintenance tasks"

    database_maintenance
    check_security_updates
    check_certificates
    verify_backups

    log "Weekly maintenance completed successfully"
}

main "$@"
EOF
}

