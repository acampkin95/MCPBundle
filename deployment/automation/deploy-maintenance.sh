# =============================================================================
# Utility Functions
# =============================================================================

log() {
    echo -e "${BLUE}[$(date +'%Y-%m-%d %H:%M:%S')]${NC} $*"
}

log_success() {
    echo -e "${GREEN}[✓]${NC} $*"
}

log_error() {
    echo -e "${RED}[✗]${NC} $*"
}

log_warning() {
    echo -e "${YELLOW}[!]${NC} $*"
}

log_header() {
    echo -e "\n${BOLD}${CYAN}═══════════════════════════════════════════════════════════════${NC}"
    echo -e "${BOLD}${CYAN}$*${NC}"
    echo -e "${BOLD}${CYAN}═══════════════════════════════════════════════════════════════${NC}\n"
}

execute_on_vm() {
    local vm_ip=$1
    shift
    local cmd="$*"

    if [ "$DRY_RUN" = true ]; then
        log "[DRY-RUN] Would execute on $vm_ip: $cmd"
        return 0
    fi

    ssh -o ConnectTimeout=10 -o StrictHostKeyChecking=no "root@${vm_ip}" "$cmd"
}

copy_to_vm() {
    local vm_ip=$1
    local local_file=$2
    local remote_file=$3

    if [ "$DRY_RUN" = true ]; then
        log "[DRY-RUN] Would copy $local_file to $vm_ip:$remote_file"
        return 0
    fi

    scp -o ConnectTimeout=10 -o StrictHostKeyChecking=no "$local_file" "root@${vm_ip}:${remote_file}"
}

# =============================================================================
# Self-Healing Service Monitor Generator
# =============================================================================

generate_service_monitor() {
    local vm_name=$1
    local services=$2

    cat << 'EOF'
#!/bin/bash
# =============================================================================
# MCP Self-Healing Service Monitor
# =============================================================================
# Automatically monitors and restarts failed services with intelligent cooldown
# Generated by deploy-maintenance.sh
# =============================================================================

set -euo pipefail

readonly STATE_DIR="/var/lib/mcp/service-monitor"
readonly LOG_FILE="/var/log/mcp/service-monitor.log"
readonly MAX_ATTEMPTS=3
readonly COOLDOWN_SECONDS=300
readonly METRICS_FILE="/var/lib/node_exporter/textfile_collector/mcp_services.prom"

# Service list
EOF

    echo "readonly SERVICES=($(echo "$services" | sed 's/,/ /g'))" >> /tmp/service-monitor-$$.sh
    cat /tmp/service-monitor-$$.sh

    cat << 'EOF'

# Initialize state directory
mkdir -p "$STATE_DIR"
mkdir -p "$(dirname "$LOG_FILE")"
mkdir -p "$(dirname "$METRICS_FILE")"

log() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*" | tee -a "$LOG_FILE"
}

# Get restart count for service
get_restart_count() {
    local service=$1
    local count_file="${STATE_DIR}/${service}.count"

    if [ -f "$count_file" ]; then
        cat "$count_file"
    else
        echo "0"
    fi
}

# Increment restart count
increment_restart_count() {
    local service=$1
    local count_file="${STATE_DIR}/${service}.count"
    local count=$(get_restart_count "$service")

    echo $((count + 1)) > "$count_file"
}

# Reset restart count
reset_restart_count() {
    local service=$1
    local count_file="${STATE_DIR}/${service}.count"

    echo "0" > "$count_file"
}

# Check if service is in cooldown
is_in_cooldown() {
    local service=$1
    local cooldown_file="${STATE_DIR}/${service}.cooldown"

    if [ -f "$cooldown_file" ]; then
        local cooldown_until=$(cat "$cooldown_file")
        local now=$(date +%s)

        if [ "$now" -lt "$cooldown_until" ]; then
            local remaining=$((cooldown_until - now))
            log "Service $service is in cooldown for $remaining more seconds"
            return 0
        else
            rm -f "$cooldown_file"
            return 1
        fi
    fi

    return 1
}

# Set cooldown period
set_cooldown() {
    local service=$1
    local cooldown_file="${STATE_DIR}/${service}.cooldown"
    local cooldown_until=$(($(date +%s) + COOLDOWN_SECONDS))

    echo "$cooldown_until" > "$cooldown_file"
    log "Service $service entering cooldown until $(date -d @$cooldown_until 2>/dev/null || date -r $cooldown_until)"
}

# Update Prometheus metrics
update_metrics() {
    local service=$1
    local status=$2
    local restarts=$(get_restart_count "$service")

    # Create metrics in Prometheus format
    {
        echo "# HELP mcp_service_status Service status (1=running, 0=stopped)"
        echo "# TYPE mcp_service_status gauge"
        echo "mcp_service_status{service=\"$service\"} $status"
        echo ""
        echo "# HELP mcp_service_restarts_total Total number of service restarts"
        echo "# TYPE mcp_service_restarts_total counter"
        echo "mcp_service_restarts_total{service=\"$service\"} $restarts"
    } >> "$METRICS_FILE.tmp"
}

# Check and heal service
check_service() {
    local service=$1

    # Check if service is active
    if systemctl is-active --quiet "$service"; then
        # Service is running
        reset_restart_count "$service"
        update_metrics "$service" 1
        return 0
    else
        # Service is not running
        log "Service $service is not running"
        update_metrics "$service" 0

        # Check if in cooldown
        if is_in_cooldown "$service"; then
            log "Service $service in cooldown, skipping restart"
            return 1
        fi

        # Check restart count
        local restart_count=$(get_restart_count "$service")

        if [ "$restart_count" -ge "$MAX_ATTEMPTS" ]; then
            log "Service $service has exceeded maximum restart attempts ($MAX_ATTEMPTS)"
            set_cooldown "$service"
            reset_restart_count "$service"

            # Send alert
            logger -p daemon.crit "MCP: Service $service failed to start after $MAX_ATTEMPTS attempts"

            return 1
        fi

        # Attempt restart
        log "Attempting to restart $service (attempt $((restart_count + 1))/$MAX_ATTEMPTS)"

        if systemctl restart "$service"; then
            log "Successfully restarted $service"
            increment_restart_count "$service"

            # Wait a bit and verify it stayed up
            sleep 5

            if systemctl is-active --quiet "$service"; then
                log "Service $service is stable after restart"
                update_metrics "$service" 1
                return 0
            else
                log "Service $service failed to stay running"
                update_metrics "$service" 0
                return 1
            fi
        else
            log "Failed to restart $service"
            increment_restart_count "$service"
            update_metrics "$service" 0
            return 1
        fi
    fi
}

# Main monitoring loop
main() {
    log "Starting MCP service monitor"

    # Initialize metrics file
    : > "$METRICS_FILE.tmp"

    # Check all services
    local failed_services=0

    for service in "${SERVICES[@]}"; do
        if ! check_service "$service"; then
            ((failed_services++)) || true
        fi
    done

    # Finalize metrics
    mv "$METRICS_FILE.tmp" "$METRICS_FILE"

    # Overall health metric
    {
        echo "# HELP mcp_service_monitor_healthy Overall health check (1=healthy, 0=issues)"
        echo "# TYPE mcp_service_monitor_healthy gauge"
        if [ "$failed_services" -eq 0 ]; then
            echo "mcp_service_monitor_healthy 1"
        else
            echo "mcp_service_monitor_healthy 0"
        fi
        echo ""
        echo "# HELP mcp_service_monitor_failed_services Number of failed services"
        echo "# TYPE mcp_service_monitor_failed_services gauge"
        echo "mcp_service_monitor_failed_services $failed_services"
    } >> "$METRICS_FILE"

    if [ "$failed_services" -gt 0 ]; then
        log "Health check completed with $failed_services failed service(s)"
        exit 1
    else
        log "All services healthy"
        exit 0
    fi
}

main "$@"
EOF

    rm -f /tmp/service-monitor-$$.sh
}

# =============================================================================
# Daily Maintenance Script Generator
# =============================================================================

generate_daily_maintenance() {
    cat << 'EOF'
#!/bin/bash
# =============================================================================
# MCP Daily Maintenance Tasks
# =============================================================================
# - Log rotation and cleanup
# - Disk space monitoring
# - Metrics collection
# - Service health verification
# =============================================================================

set -euo pipefail

readonly LOG_DIR="/var/log/mcp"
readonly LOG_RETENTION_DAYS=30
readonly DISK_WARNING_THRESHOLD=80
readonly DISK_CRITICAL_THRESHOLD=90
readonly METRICS_FILE="/var/lib/node_exporter/textfile_collector/mcp_daily_maintenance.prom"

log() {
    echo "[$(date +'%Y-%m-%d %H:%M:%S')] $*" | tee -a "${LOG_DIR}/daily-maintenance.log"
}

# Clean old logs
cleanup_logs() {
    log "Cleaning logs older than $LOG_RETENTION_DAYS days..."

    local deleted_count=0

    # Clean MCP logs
    if [ -d "$LOG_DIR" ]; then
        deleted_count=$(find "$LOG_DIR" -name "*.log" -type f -mtime +$LOG_RETENTION_DAYS -delete -print | wc -l)
        log "Deleted $deleted_count old MCP log files"
    fi

    # Clean journald
    journalctl --vacuum-time=${LOG_RETENTION_DAYS}d >/dev/null 2>&1 || true

    # Clean old compressed logs
    find /var/log -name "*.gz" -type f -mtime +$LOG_RETENTION_DAYS -delete 2>/dev/null || true

    log "Log cleanup completed"
}

# Check disk space
check_disk_space() {
    log "Checking disk space..."

    local partitions=("/" "/var" "/opt" "/mnt/storage" "/tmp")
    local warning_count=0
    local critical_count=0

    for partition in "${partitions[@]}"; do
        if ! mountpoint -q "$partition" 2>/dev/null && [ "$partition" != "/" ]; then
            continue
        fi

        local usage=$(df -h "$partition" | tail -1 | awk '{print $5}' | sed 's/%//')
        local available=$(df -h "$partition" | tail -1 | awk '{print $4}')

        log "Partition $partition: ${usage}% used, ${available} available"

        # Update metrics
        echo "mcp_disk_usage_percent{partition=\"$partition\"} $usage" >> "$METRICS_FILE.tmp"

        if [ "$usage" -ge "$DISK_CRITICAL_THRESHOLD" ]; then
            log "CRITICAL: Partition $partition is ${usage}% full"
            logger -p daemon.crit "MCP: Disk space critical on $partition (${usage}% used)"
            ((critical_count++)) || true
        elif [ "$usage" -ge "$DISK_WARNING_THRESHOLD" ]; then
            log "WARNING: Partition $partition is ${usage}% full"
            logger -p daemon.warning "MCP: Disk space warning on $partition (${usage}% used)"
            ((warning_count++)) || true
        fi
    done

    # Overall disk health metric
    if [ "$critical_count" -gt 0 ]; then
        echo "mcp_disk_health 0" >> "$METRICS_FILE.tmp"
    elif [ "$warning_count" -gt 0 ]; then
        echo "mcp_disk_health 1" >> "$METRICS_FILE.tmp"
    else
        echo "mcp_disk_health 2" >> "$METRICS_FILE.tmp"
    fi

    log "Disk space check completed"
}

# Collect system metrics
collect_metrics() {
    log "Collecting system metrics..."

    mkdir -p "$(dirname "$METRICS_FILE")"
    : > "$METRICS_FILE.tmp"

    # CPU load
    local load1=$(uptime | awk -F'load average:' '{print $2}' | awk -F',' '{print $1}' | xargs)
    echo "mcp_system_load1 $load1" >> "$METRICS_FILE.tmp"

    # Memory usage
    local mem_total=$(free -b | awk '/Mem:/ {print $2}')
    local mem_used=$(free -b | awk '/Mem:/ {print $3}')
    local mem_percent=$((mem_used * 100 / mem_total))
    echo "mcp_memory_usage_percent $mem_percent" >> "$METRICS_FILE.tmp"

    # Process count
    local process_count=$(ps aux | wc -l)
    echo "mcp_process_count $process_count" >> "$METRICS_FILE.tmp"

    # Check disk space (adds to metrics)
    check_disk_space

    # Finalize metrics
    {
        echo "# HELP mcp_daily_maintenance_timestamp Unix timestamp of last daily maintenance"
        echo "# TYPE mcp_daily_maintenance_timestamp gauge"
        echo "mcp_daily_maintenance_timestamp $(date +%s)"
    } >> "$METRICS_FILE.tmp"

    mv "$METRICS_FILE.tmp" "$METRICS_FILE"

    log "Metrics collection completed"
}

# Verify service health
verify_services() {
    log "Verifying service health..."

    local failed_services=$(systemctl list-units --state=failed --no-pager --no-legend | wc -l)

    if [ "$failed_services" -gt 0 ]; then
        log "WARNING: $failed_services failed service(s) detected"
        systemctl list-units --state=failed --no-pager | tee -a "${LOG_DIR}/daily-maintenance.log"
    else
        log "All services operational"
    fi
}

# Main execution
main() {
    log "Starting daily maintenance tasks"

    cleanup_logs
    collect_metrics
    verify_services

    log "Daily maintenance completed successfully"
}

main "$@"
EOF
}

