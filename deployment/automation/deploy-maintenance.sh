generate_service_monitor_systemd() {
    cat << EOF
[Unit]
Description=MCP Self-Healing Service Monitor
After=network.target

[Service]
Type=oneshot
ExecStart=${DEPLOY_DIR}/service-monitor.sh
StandardOutput=journal
StandardError=journal
SyslogIdentifier=mcp-service-monitor

[Install]
WantedBy=multi-user.target
EOF
}

generate_service_monitor_timer() {
    cat << EOF
[Unit]
Description=MCP Service Monitor Timer (every ${HEALTH_CHECK_INTERVAL}s)

[Timer]
OnBootSec=30s
OnUnitActiveSec=${HEALTH_CHECK_INTERVAL}s
AccuracySec=1s

[Install]
WantedBy=timers.target
EOF
}

