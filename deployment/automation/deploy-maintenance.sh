declare -A VM_SERVICES=(
    ["vmi01"]="postgresql,mcp-orchestrator,perplexity-mcp,itjsst-mcp,redis-server,pgbouncer"
    ["vmi02d"]="postgresql,mcp-storage"
    ["vmi03"]="haproxy,prometheus,grafana,nginx,pihole-FTL"
)

