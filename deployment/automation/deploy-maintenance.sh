#!/bin/bash
set -euo pipefail

# =============================================================================
# MCP Bundle Automated Maintenance Deployment
# =============================================================================
# Deploy comprehensive self-healing and maintenance automation across all VMs
#
# Features:
# - Self-healing service monitors (10s intervals)
# - Auto-restart failed services (max 3 attempts, 5min cooldown)
# - Prometheus metrics integration
# - Scheduled maintenance tasks:
#   - Daily: Log cleanup, disk space monitoring, metrics collection
#   - Weekly: Database VACUUM, security update checks
#   - Monthly: Full optimization, backup verification
# - Systemd service and timer management
#
# Usage: ./deploy-maintenance.sh [options]
# Options:
#   --vm <vm>       Deploy to specific VM only (vmi01, vmi02d, vmi03, all)
#   --service-only  Deploy only service monitors
#   --cron-only     Deploy only scheduled tasks
#   --dry-run       Show what would be deployed without making changes
# =============================================================================

# Color codes for output
readonly RED='\033[0;31m'
readonly GREEN='\033[0;32m'
readonly YELLOW='\033[1;33m'
readonly BLUE='\033[0;34m'
readonly CYAN='\033[0;36m'
readonly NC='\033[0m' # No Color
readonly BOLD='\033[1m'

# VM Configuration
declare -A VMS=(
    ["vmi01"]="46.250.243.123"
    ["vmi02d"]="46.250.241.70"
    ["vmi03"]="154.26.158.31"
