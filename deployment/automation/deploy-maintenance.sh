# =============================================================================
# Deployment Functions
# =============================================================================

deploy_to_vm() {
    local vm_name=$1
    local vm_ip=$2

    log_header "Deploying to $vm_name ($vm_ip)"

    # Create directories
    log "Creating deployment directories..."
    execute_on_vm "$vm_ip" "mkdir -p ${DEPLOY_DIR} ${LOG_DIR} /var/lib/mcp/service-monitor /var/lib/mcp/reports /var/lib/node_exporter/textfile_collector"

    # Deploy service monitor
    if [ "$CRON_ONLY" != true ]; then
        log "Deploying self-healing service monitor..."

        local services="${VM_SERVICES[$vm_name]}"
        local monitor_script="/tmp/service-monitor-${vm_name}.sh"

        generate_service_monitor "$vm_name" "$services" > "$monitor_script"
        copy_to_vm "$vm_ip" "$monitor_script" "${DEPLOY_DIR}/service-monitor.sh"
        execute_on_vm "$vm_ip" "chmod +x ${DEPLOY_DIR}/service-monitor.sh"

        # Deploy systemd service and timer
        generate_service_monitor_systemd | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-service-monitor.service"
        generate_service_monitor_timer | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-service-monitor.timer"

        rm -f "$monitor_script"

        log_success "Service monitor deployed"
    fi

    # Deploy scheduled maintenance
    if [ "$SERVICE_ONLY" != true ]; then
        log "Deploying scheduled maintenance tasks..."

        # Daily maintenance
        local daily_script="/tmp/daily-maintenance.sh"
        generate_daily_maintenance > "$daily_script"
        copy_to_vm "$vm_ip" "$daily_script" "${DEPLOY_DIR}/daily-maintenance.sh"
        execute_on_vm "$vm_ip" "chmod +x ${DEPLOY_DIR}/daily-maintenance.sh"
        rm -f "$daily_script"

        generate_maintenance_service "daily" "daily-maintenance.sh" | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-daily-maintenance.service"
        generate_daily_maintenance_timer | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-daily-maintenance.timer"

        # Weekly maintenance
        local weekly_script="/tmp/weekly-maintenance.sh"
        generate_weekly_maintenance > "$weekly_script"
        copy_to_vm "$vm_ip" "$weekly_script" "${DEPLOY_DIR}/weekly-maintenance.sh"
        execute_on_vm "$vm_ip" "chmod +x ${DEPLOY_DIR}/weekly-maintenance.sh"
        rm -f "$weekly_script"

        generate_maintenance_service "weekly" "weekly-maintenance.sh" | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-weekly-maintenance.service"
        generate_weekly_maintenance_timer | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-weekly-maintenance.timer"

        # Monthly maintenance
        local monthly_script="/tmp/monthly-maintenance.sh"
        generate_monthly_maintenance > "$monthly_script"
        copy_to_vm "$vm_ip" "$monthly_script" "${DEPLOY_DIR}/monthly-maintenance.sh"
        execute_on_vm "$vm_ip" "chmod +x ${DEPLOY_DIR}/monthly-maintenance.sh"
        rm -f "$monthly_script"

        generate_maintenance_service "monthly" "monthly-maintenance.sh" | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-monthly-maintenance.service"
        generate_monthly_maintenance_timer | execute_on_vm "$vm_ip" "cat > /etc/systemd/system/mcp-monthly-maintenance.timer"

        log_success "Scheduled maintenance deployed"
    fi

    # Reload systemd and enable services
    if [ "$DRY_RUN" != true ]; then
        log "Enabling and starting services..."

        execute_on_vm "$vm_ip" "systemctl daemon-reload"

        if [ "$CRON_ONLY" != true ]; then
            execute_on_vm "$vm_ip" "systemctl enable --now mcp-service-monitor.timer"
            log_success "Service monitor enabled"
        fi

        if [ "$SERVICE_ONLY" != true ]; then
            execute_on_vm "$vm_ip" "systemctl enable --now mcp-daily-maintenance.timer"
            execute_on_vm "$vm_ip" "systemctl enable --now mcp-weekly-maintenance.timer"
            execute_on_vm "$vm_ip" "systemctl enable --now mcp-monthly-maintenance.timer"
            log_success "Maintenance timers enabled"
        fi

        # Show status
        log "Deployment status:"
        execute_on_vm "$vm_ip" "systemctl list-timers 'mcp-*' --no-pager"
    fi

    log_success "Deployment to $vm_name completed"
}

# =============================================================================
# Main Execution
# =============================================================================

print_usage() {
    cat << EOF
Usage: $0 [options]

Options:
  --vm <vm>       Deploy to specific VM (vmi01, vmi02d, vmi03, all)
  --service-only  Deploy only self-healing service monitors
  --cron-only     Deploy only scheduled maintenance tasks
  --dry-run       Show what would be deployed without making changes
  -h, --help      Show this help message

Examples:
  $0                      # Deploy everything to all VMs
  $0 --vm vmi01           # Deploy to VMI01 only
  $0 --service-only       # Deploy only service monitors
  $0 --dry-run            # Preview deployment without changes

EOF
}

main() {
    # Parse arguments
    while [[ $# -gt 0 ]]; do
        case $1 in
            --vm)
                TARGET_VM="$2"
                if [ "$TARGET_VM" != "all" ] && [ -z "${VMS[$TARGET_VM]:-}" ]; then
                    log_error "Unknown VM '$TARGET_VM'. Valid options: ${!VMS[@]} all"
                    exit 1
                fi
                shift 2
                ;;
            --service-only)
                SERVICE_ONLY=true
                shift
                ;;
            --cron-only)
                CRON_ONLY=true
                shift
                ;;
            --dry-run)
                DRY_RUN=true
                shift
                ;;
            -h|--help)
                print_usage
                exit 0
                ;;
            *)
                log_error "Unknown option: $1"
                print_usage
                exit 1
                ;;
        esac
    done

    log_header "MCP Automated Maintenance Deployment"
    log "Target: $TARGET_VM"
    log "Service Monitor: $([ "$CRON_ONLY" = true ] && echo "Skip" || echo "Deploy")"
    log "Scheduled Tasks: $([ "$SERVICE_ONLY" = true ] && echo "Skip" || echo "Deploy")"
    log "Dry Run: $DRY_RUN"

    # Deploy to each VM
    for vm_name in "${!VMS[@]}"; do
        if [ "$TARGET_VM" != "all" ] && [ "$TARGET_VM" != "$vm_name" ]; then
            continue
        fi

        vm_ip="${VMS[$vm_name]}"
        deploy_to_vm "$vm_name" "$vm_ip"
    done

    log_header "Deployment Complete"

    if [ "$DRY_RUN" = true ]; then
        log_warning "DRY RUN MODE - No changes were made"
    else
        log_success "All maintenance automation deployed successfully"
        log ""
        log "Deployed components:"
        [ "$CRON_ONLY" != true ] && log "  - Self-healing service monitors (${HEALTH_CHECK_INTERVAL}s interval)"
        [ "$SERVICE_ONLY" != true ] && log "  - Daily maintenance (02:00 every day)"
        [ "$SERVICE_ONLY" != true ] && log "  - Weekly maintenance (03:00 every Sunday)"
        [ "$SERVICE_ONLY" != true ] && log "  - Monthly maintenance (04:00 on 1st of month)"
        log ""
        log "Monitor status with:"
        log "  systemctl list-timers 'mcp-*'"
        log "  journalctl -u mcp-service-monitor -f"
        log "  tail -f ${LOG_DIR}/*.log"
    fi

    exit 0
}

# Run main function
main "$@"
