# Performance analysis
performance_analysis() {
    log "Performing performance analysis..."

    local perf_report="${REPORT_DIR}/performance-$(date +%Y%m).txt"

    {
        echo "==================================="
        echo "MCP Performance Analysis Report"
        echo "Generated: $(date)"
        echo "==================================="
        echo ""

        echo "I/O Statistics:"
        echo "-----------------------------------"
        iostat -x 1 5 2>/dev/null || echo "iostat not available"
        echo ""

        echo "Network Statistics:"
        echo "-----------------------------------"
        netstat -s 2>/dev/null || ss -s
        echo ""

        if systemctl is-active --quiet postgresql; then
            echo "Database Statistics:"
            echo "-----------------------------------"
            sudo -u postgres psql -d postgres << 'SQL'
SELECT
    datname,
    numbackends as connections,
    xact_commit as commits,
    xact_rollback as rollbacks,
    blks_read as blocks_read,
    blks_hit as blocks_hit,
    tup_returned as tuples_returned,
    tup_fetched as tuples_fetched,
    tup_inserted as tuples_inserted,
    tup_updated as tuples_updated,
    tup_deleted as tuples_deleted
FROM pg_stat_database
WHERE datname NOT IN ('template0', 'template1');
SQL
            echo ""

            echo "Slow Queries (if pg_stat_statements enabled):"
            echo "-----------------------------------"
            sudo -u postgres psql -d postgres -c "SELECT query, calls, total_time, mean_time FROM pg_stat_statements ORDER BY mean_time DESC LIMIT 10;" 2>/dev/null || echo "pg_stat_statements not enabled"
            echo ""
        fi

    } > "$perf_report"

    log "Performance report saved to: $perf_report"
}

